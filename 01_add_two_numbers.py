# How to Add Two Numbers in Python

# Method 1: Using + operator
a = 15
b = 12

res = a + b

print(res)


# Method 2: Using sum()
nums = [10, 5]

print(sum(nums))


# Method 3: Using operator.add()
import operator

print(operator.add(10, 5))


# Method 4: Using math.fsum()
import math

nums = [0.1, 0.2]

print(math.fsum(nums))
